#!/usr/bin/env python3
"""Internal Affairs: run the attack corpus through the real cop-hook binary.

PLAN:
1. Load corpus.jsonl (one case per line).
2. For each case, run target/debug/cop-hook with the hook JSON on stdin, a temp HOME, and AGENTCOP_POLICY=policy/default.toml.
3. Read permissionDecision from stdout. No parseable answer = "error" (never a pass).
4. Outcome: PASS, FAIL, XFAIL (known gap, still missed), or XPASS (known gap now passes, which fails the suite so the marker is removed).
5. Add the detective-injection cases (detective_injection.py).
6. Write docs/internal-affairs.md (no timestamps, so reruns match) and exit 1 on any FAIL or XPASS.
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
HOOK = Path(os.environ.get("AGENTCOP_HOOK_BIN", ROOT / "target/debug/cop-hook"))
POLICY = ROOT / "policy/default.toml"
CORPUS = HERE / "corpus.jsonl"
REPORT = ROOT / "docs/internal-affairs.md"

sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "detective"))
import detective_injection  # noqa: E402


def load_corpus():
    return [json.loads(line) for line in CORPUS.read_text(encoding="utf-8").splitlines() if line.strip()]


def hook_verdict(case, home):
    event = {
        "hook_event_name": "PreToolUse",
        # One session per case. Rule of Two state would otherwise carry from one case into the next.
        "session_id": f"attack-{case['id']}",
        "timestamp": "2026-10-23T00:00:00Z",
        "tool_name": case["tool_name"],
        "tool_input": case["tool_input"],
    }
    env = {"HOME": home, "PATH": os.environ.get("PATH", ""), "AGENTCOP_POLICY": str(POLICY)}
    proc = subprocess.run(
        [str(HOOK)], input=json.dumps(event), capture_output=True, text=True, env=env, timeout=10
    )
    try:
        return json.loads(proc.stdout)["hookSpecificOutput"]["permissionDecision"]
    except (ValueError, KeyError, TypeError):
        return "error"


def outcome(expect, got, xfail):
    if xfail:
        return "XFAIL" if got != expect else "XPASS"
    return "PASS" if got == expect else "FAIL"


def run_hook_cases():
    rows = []
    for case in load_corpus():
        # 2026-10-27: a fresh HOME per case, so no state (sessions, evidence) carries from one case to the next.
        with tempfile.TemporaryDirectory() as home:
            got = hook_verdict(case, home)
        rows.append({
            "id": case["id"],
            "category": case["category"],
            "expect": case["expect"],
            "got": got,
            "result": outcome(case["expect"], got, case.get("xfail")),
            "note": case.get("note", ""),
            "xfail": case.get("xfail", ""),
        })
    return rows


def render(rows):
    counts = {k: sum(1 for r in rows if r["result"] == k) for k in ("PASS", "FAIL", "XFAIL", "XPASS")}
    lines = [
        "# Internal Affairs results",
        "",
        "Generated by `tests/attacks/run_attacks.py` (run from `scripts/check.sh`). Do not edit by hand.",
        "",
        f"Cases: {len(rows)}. PASS: {counts['PASS']}. XFAIL (known gaps): {counts['XFAIL']}. FAIL: {counts['FAIL']}. XPASS: {counts['XPASS']}.",
        "",
        "| id | category | expect | got | result | note |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        lines.append(f"| {r['id']} | {r['category']} | {r['expect']} | {r['got']} | {r['result']} | {r['note']} |")
    gaps = [r for r in rows if r["xfail"]]
    if gaps:
        lines += ["", "## Known gaps", ""]
        lines += [f"- **{r['id']}**: {r['xfail']}" for r in gaps]
    lines += [
        "",
        "## What this does not cover",
        "",
        "- Only the built-in policy is tested. Your own rules are not.",
        "- Only the cases in this corpus. A passing run is not proof of safety.",
        "",
    ]
    return "\n".join(lines), counts


def main():
    if not HOOK.exists():
        print(f"cop-hook not found at {HOOK}; run cargo build -p cop-hook first", file=sys.stderr)
        return 2
    rows = run_hook_cases() + detective_injection.run_cases()
    text, counts = render(rows)
    REPORT.write_text(text, encoding="utf-8")
    for r in rows:
        if r["result"] in ("FAIL", "XPASS"):
            print(f"{r['result']} {r['id']}: expected {r['expect']}, got {r['got']}", file=sys.stderr)
    print(f"Internal Affairs: {counts['PASS']} pass, {counts['XFAIL']} known gaps, {counts['FAIL']} fail, {counts['XPASS']} xpass")
    return 1 if counts["FAIL"] or counts["XPASS"] else 0


if __name__ == "__main__":
    sys.exit(main())
